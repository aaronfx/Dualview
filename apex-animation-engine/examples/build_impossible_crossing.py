def _event(events, name, who="iko"):
    matches = [e.t for e in events if e.type == name and e.character == who]
    return matches[0] if matches else None


def _shots(events, duration, chosen):
    climb_start = _event(events, "climb_start")
    climbed = _event(events, "climbed")
    takeoff = _event(events, "takeoff")
    impact = _event(events, "impact")
    pickup = _event(events, "pick_up")
    if pickup is None or impact is None:
        raise ValueError("selected plan has no real pickup and impact events")
    if chosen in ("climb_then_drop", "shift_crate_then_climb"):
        if climb_start is None or climbed is None or takeoff is None:
            raise ValueError("climbing route is missing mandatory physical milestones")
        # Fast actors can reach the obstacle before the old fixed-length
        # opening has finished. Cut the establishing shot earlier rather
        # than slowing the performer or creating an unreadably short scene.
        establish_end = min(0.82, max(0.39, climb_start - 0.67))
        edges = [0, round(establish_end, 3), round(climb_start - 0.20, 3),
                 round(climbed + 0.1, 3), round(impact + 0.18, 3),
                 round(pickup - 0.18, 3), duration]
        specs = [
            ("s01_goal", "establishing", "original broken path, barrier, supply crate and distant symbol",
             {"mode": "static", "center": [-35, 245], "view_height": 770}),
            ("s02_decision", "medium", "IKO tries to reason about the impassable leap, gathers courage",
             {"mode": "follow", "target": "iko", "view_height": 460, "offset": [30, 40],
              "lead": 0.10, "stiffness": 4.0}),
            ("s03_climb", "medium", "the engine-selected alternative: reach the edge and climb with hand contact",
             {"mode": "follow", "target": "iko", "view_height": 580, "offset": [60, 40],
              "lead": 0.16, "stiffness": 3.7}),
            ("s04_drop", "wide", "fall and landing are determined by APEX gravity and contact",
             {"mode": "follow", "target": "iko", "view_height": 630, "offset": [85, 30],
              "lead": 0.25, "stiffness": 3.5}),
            ("s05_recovery", "medium", "impact absorption, breathing and searching for the reward",
             {"mode": "follow", "target": "iko", "view_height": 420, "offset": [35, 30],
              "lead": 0.11, "stiffness": 4.0}),
            ("s06_payoff", "medium", "the reward is really picked up; no simulated outcome is faked",
             {"mode": "follow", "target": "iko", "view_height": 380, "offset": [0, 35],
              "lead": 0.08, "stiffness": 4.0})
        ]
    else:
        # Same goal, another tactic. Event-driven cuts are meaningful without
        # assuming the planner always chooses a climb.
        decisive = _event(events, "vault_start") or takeoff or 2.0
        edges = [0, 0.82, round(decisive - 0.2, 3), round(impact + 0.12, 3),
                 round(pickup - 0.15, 3), duration]
        specs = [
            ("s01_goal", "establishing", "path and reward", {"mode": "static", "center": [-25, 245], "view_height": 760}),
            ("s02_decision", "medium", "the performer chooses a viable route",
             {"mode": "follow", "target": "iko", "view_height": 470, "offset": [35, 35]}),
            ("s03_action", "wide", "the chosen action must be physically executed",
             {"mode": "follow", "target": "iko", "view_height": 600, "offset": [45, 45]}),
            ("s04_approach", "medium", "recover and reach the objective",
             {"mode": "follow", "target": "iko", "view_height": 440, "offset": [45, 40]}),
            ("s05_payoff", "medium", "physical glyph pickup",
             {"mode": "follow", "target": "iko", "view_height": 370, "offset": [0, 35]})
        ]
    if any(b - a < 0.38 for a, b in zip(edges, edges[1:])):
        raise ValueError(f"automatic shot timing too tight; events: {edges}")
    shots = []
    for i, (sid, kind, desc, camera) in enumerate(specs):
        shots.append({"id": sid, "kind": kind, "description": desc,
                      "start": edges[i], "end": edges[i+1], "camera": camera})
    shots[-1]["fade_out"] = 0.65
    return shots


def build():
    obj = Objective(scene_id="cross", actor="iko", obstacle_id="barrier",
                    goal_prop_id="spark", movable_prop_id="crate",
                    max_trial_seconds=19, max_jump_apex=210,
                    prefer_prop_interaction=True, pacing="active")
    original = ProjectSpec.model_validate(world())
    result = search(original, obj)
    if not result.succeeded:
        raise ValueError("no physical route worked: " + json.dumps(result.report()))
    # Execute winning full action list from scratch in the actual scene:
    # planning trial results are not substituted for physics.
    raw = world()
    sc = raw["scenes"][0]
    sc["actions"] = list(result.actions)
    sc["goals"] = ["notice@iko", "act@iko[clip=doubt_to_dash]"]
    if "climb" in result.chosen:
        sc["goals"] += ["climbed@iko", "takeoff@iko", "impact@iko"]
    elif "vault" in result.chosen:
        sc["goals"] += ["vault@iko", "impact@iko"]
    else:
        sc["goals"] += ["takeoff@iko", "impact@iko"]
    sc["goals"].append("pick_up@iko[prop=spark]")
    staged = ProjectSpec.model_validate(raw)
    sim = SceneRuntime(staged, "cross").simulate(physics_only=True)
    pick = _event(sim.events, "pick_up")
    if pick is None:
        raise ValueError("the chosen trial stopped reproducing its goal during staging")
    # Keep the complete quick celebration and a readable fade, not seconds of dead air.
    duration = math.ceil((pick + actor_pace(obj.pacing).final_tail) * staged.fps) / staged.fps
    if duration > 19:
        raise ValueError("selected plan too slow for film budget")
    raw["scenes"][0]["duration"] = duration
    raw["scenes"][0]["shots"] = _shots(sim.events, duration, result.chosen)
    return ProjectSpec.model_validate(raw), result


if __name__ == "__main__":
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "out/impossible_crossing.json")
    path.parent.mkdir(parents=True, exist_ok=True)
    project, plan = build()
    from apex.ai.director import StoryDirector
    StoryDirector._dry_run(project)
    path.write_text(project.model_dump_json(indent=2, exclude_defaults=True), encoding="utf-8")
    report_path = path.with_suffix(".plan.json")
    report_path.write_text(json.dumps(plan.report(), indent=2), encoding="utf-8")
    print(f"winner: {plan.chosen} — {len(plan.trials)} tactics evaluated")
    for t in plan.trials:
        print(f"  {t.candidate:25s} {'ACCEPT' if t.accepted else 'REJECT'}: {t.reason}")
    print(f"film: {project.scenes[0].duration:.2f}s; proof trace: {report_path}")
